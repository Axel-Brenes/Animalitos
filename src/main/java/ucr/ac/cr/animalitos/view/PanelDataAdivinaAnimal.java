    //**********metodo para reproducir sonidos*************
    private void reproducirSonido(String archivo) {

        new Thread(() -> {
            try {
                InputStream sonido = getClass()
                        .getResourceAsStream("/" + archivo);

                if (sonido != null) {
                    Player reproductor = new Player(sonido);
                    reproductor.play();
                } else {
                    System.out.println("No se encontró el sonido");
                }

            } catch (Exception e) {
                System.out.println("Error al reproducir el sonido");
            }
        }).start();
    }
    
    //****************seleccion aleatoria****************
    private void seleccionarAnimal() {

        if (cantidadUsados == 4) {
            lblMensaje.setText("¡Felicidades! Completaste el juego");
            return;
        }

        int posicion;

        do {
            posicion = (int) (Math.random() * animales.length);
            animalActual = animales[posicion];

        } while (animalYaUsado(animalActual));

        animalesUsados[cantidadUsados] = animalActual;
        cantidadUsados++;

        lblNivel.setText("Nivel " + nivel);
        lblMensaje.setText("Escucha el sonido y adivina");
    }
    
    //************evita repetir animales al jugar*******************
    private boolean animalYaUsado(String animal) {

        for (int i = 0; i < cantidadUsados; i++) {

            if (animalesUsados[i].equals(animal)) {
                return true;
            }
        }

        return false;
    }
    
    //**************este metodo es para comprobar las respuestas********************
    private void comprobarRespuesta(String respuesta) {

    if (animalActual.equals(respuesta)) {

        lblMensaje.setText("¡Correcto! Muy bien");

        nivel++;

        if (cantidadUsados == 4) {
            lblMensaje.setText("¡Felicidades! Completaste los 4 niveles");
            return;
        }

        seleccionarAnimal();

    } else {

        lblMensaje.setText("Incorrecto. Intenta nuevamente");

        nivel = 1;
        cantidadUsados = 0;
        animalActual = null;

        seleccionarAnimal();
    }
}
    
    
